def turn(regional, english, expectation, exact=None):
    result = {'prompts': {'regional': regional, 'en': english}, 'expectation': expectation}
    if exact is not None:
        result['exact'] = exact
    return result


def case(key, title, character, focus, turns, quick=False):
    return {'id': key, 'title': title, 'character': character,
            'track': 'patient' if character else 'reasoning', 'focus': focus,
            'quick': quick, 'turns': turns}


